/**
 * Reads backend seed JSON files and generates typed mock data for the frontend.
 *
 * Usage: node calimali-app/scripts/generate-mock-exercises.js
 *
 * Outputs:
 *   services/api/__mocks__/exercises.generated.ts
 *   services/api/__mocks__/categories.generated.ts
 */

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const SEED_DIR = path.resolve(
  __dirname,
  "../../calimali-backend/CalimaliAPI/seed",
);
const OUT_DIR = path.resolve(
  __dirname,
  "../services/api/__mocks__",
);

// Deterministic UUID from a string (code)
function codeToUuid(code) {
  const hash = crypto.createHash("md5").update(code).digest("hex");
  return [
    hash.slice(0, 8),
    hash.slice(8, 12),
    "4" + hash.slice(13, 16), // version 4
    "8" + hash.slice(17, 20), // variant
    hash.slice(20, 32),
  ].join("-");
}

// Read categories
const categoriesRaw = JSON.parse(
  fs.readFileSync(path.join(SEED_DIR, "system/categories.json"), "utf8"),
);

// Build category lookup: slug (lowercase) -> { id, slug, name, orderIndex }
const categoryMap = {};
categoriesRaw.forEach((cat, idx) => {
  categoryMap[cat.slug.toLowerCase()] = {
    id: idx + 1,
    slug: cat.slug,
    name: cat.name,
    orderIndex: cat.orderIndex,
  };
});

// Read all exercise seed files
const exerciseFiles = fs
  .readdirSync(path.join(SEED_DIR, "exercises"))
  .filter((f) => f.endsWith(".json"));

const allSeedExercises = [];
for (const file of exerciseFiles) {
  const data = JSON.parse(
    fs.readFileSync(path.join(SEED_DIR, "exercises", file), "utf8"),
  );
  allSeedExercises.push(...data);
}

// Build code -> UUID lookup for baseCode resolution
const codeToId = {};
for (const ex of allSeedExercises) {
  codeToId[ex.code] = codeToUuid(ex.code);
}

// Transform exercises
const exercises = allSeedExercises.map((ex) => {
  const catKey = ex.category.toLowerCase();
  const category = categoryMap[catKey];
  if (!category) {
    throw new Error(`Unknown category "${ex.category}" for exercise "${ex.code}"`);
  }

  return {
    id: codeToId[ex.code],
    name: ex.name,
    category,
    baseExerciseId: ex.baseCode ? codeToId[ex.baseCode] : undefined,
    difficulty: ex.difficulty,
    description: ex.description || "",
    equipment: ex.equipment,
    default_reps: ex.defaultReps,
    unit: ex.unit,
    is_unilateral: ex.isUnilateral,
    muscleGroups: (ex.muscles || []).map((m) => ({
      muscleDescription: m.muscleCode,
      impact: m.impact,
      effect: m.effect,
    })),
  };
});

// --- Generate exercises.generated.ts ---

function serializeExercise(ex) {
  const lines = [];
  lines.push("  {");
  lines.push(`    id: "${ex.id}",`);
  lines.push(`    name: ${JSON.stringify(ex.name)},`);
  lines.push(`    category: { id: ${ex.category.id}, slug: "${ex.category.slug}", name: "${ex.category.name}", orderIndex: ${ex.category.orderIndex} },`);
  if (ex.baseExerciseId) {
    lines.push(`    baseExerciseId: "${ex.baseExerciseId}",`);
  }
  lines.push(`    difficulty: ${JSON.stringify(ex.difficulty)} as ExerciseDifficulty,`);
  lines.push(`    description: ${JSON.stringify(ex.description)},`);
  lines.push(`    equipment: ${JSON.stringify(ex.equipment)} as ExerciseEquipment,`);
  lines.push(`    default_reps: ${ex.default_reps},`);
  lines.push(`    unit: ${JSON.stringify(ex.unit)} as ExerciseUnit,`);
  lines.push(`    is_unilateral: ${ex.is_unilateral},`);
  lines.push(`    muscleGroups: [`);
  for (const mg of ex.muscleGroups) {
    lines.push(`      { muscleDescription: "${mg.muscleDescription}", impact: ${mg.impact} as ExerciseImpact, effect: "${mg.effect}" as ExerciseEffect },`);
  }
  lines.push(`    ],`);
  lines.push("  }");
  return lines.join("\n");
}

const exercisesTs = `// Auto-generated by scripts/generate-mock-exercises.js — do not edit manually
import { Exercise } from "@/constants/Types";
import {
  ExerciseDifficulty,
  ExerciseEffect,
  ExerciseEquipment,
  ExerciseImpact,
  ExerciseUnit,
} from "@/constants/Enums";
import { createMockStore } from "./utils";

const MOCK_EXERCISES: Exercise[] = [
${exercises.map(serializeExercise).join(",\n")}
];

export const mockExerciseStore = createMockStore(MOCK_EXERCISES);
export default MOCK_EXERCISES;
`;

// --- Generate categories.generated.ts ---

const categoriesTs = `// Auto-generated by scripts/generate-mock-exercises.js — do not edit manually
import { ExerciseCategoryModel } from "@/constants/Types";

const MOCK_CATEGORIES: ExerciseCategoryModel[] = [
${Object.values(categoryMap)
  .sort((a, b) => a.orderIndex - b.orderIndex)
  .map(
    (c) =>
      `  { id: ${c.id}, slug: "${c.slug}", name: "${c.name}", orderIndex: ${c.orderIndex} }`,
  )
  .join(",\n")}
];

export default MOCK_CATEGORIES;
`;

// Write files
fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(path.join(OUT_DIR, "exercises.generated.ts"), exercisesTs);
fs.writeFileSync(path.join(OUT_DIR, "categories.generated.ts"), categoriesTs);

console.log(`Generated ${exercises.length} exercises across ${Object.keys(categoryMap).length} categories`);
console.log(`  -> ${path.join(OUT_DIR, "exercises.generated.ts")}`);
console.log(`  -> ${path.join(OUT_DIR, "categories.generated.ts")}`);
